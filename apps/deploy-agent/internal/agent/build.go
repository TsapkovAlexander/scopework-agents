// Сборка образов приложения из репозитория.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ШАГ. Синтетический compose объявляет `build:` и не объявляет
// `image:` (git.go), поэтому имя образа назначает сам compose — `<проект>-app`.
// `docker compose up` собирает образ, только если его НЕТ. После первого выката
// он есть всегда, и дальше происходило вот что: FetchRepo честно подтягивал
// свежий коммит, `up` поднимал контейнер из образа, собранного месяц назад,
// health gate его пропускал, а история релизов записывала успех. Отличить это
// от рабочего выката было нельзя ниоткуда — ровно тот класс тихой аварии,
// из-за которого платформа запретила молчаливый тег `:latest`.
//
// Сборка вынесена в собственную фазу, а не сделана флагом `up --build`, по двум
// причинам. Пользователю видно, на чём именно всё встало: ошибка компиляции и
// ошибка старта контейнера — разные починки, а в общем выводе `up --build` они
// сливаются. И отчёт о ходе получает честный этап: сборка тяжёлого образа
// занимает минуты, в течение которых «Разворачивается» без подробностей гонит
// человека смотреть логи по SSH — туда, куда платформа его пускать не должна.
//
// ЧЕГО ЗДЕСЬ НЕТ. Флага `--pull`, обновляющего базовые образы (`FROM node:20`
// разрешается в локально закешированный слой и может отставать месяцами). Это
// настоящая, но ДРУГАЯ несвежесть, и лечится она радаром обновлений, а не
// здесь: `--pull` поставил бы каждую сборку в зависимость от доступности
// реестра, а первый же боевой прогон платформы уже упирался в 429 от Docker Hub
// на анонимном лимите подсети провайдера. Ломать работающие выкаты ради
// свежести базового слоя — несоразмерная цена.

// needsImageBuild — надо ли собирать образы перед подъёмом.
//
// Только приложения из репозитория и только те, чей стек вообще что-то
// собирает:
//
//   - dockerfile — образ строим мы, это основной пострадавший случай;
//   - compose — описание пишет клиент, и `build:` в нём compose-guard не
//     запрещает (в composeService такого поля нет вовсе), значит репозиторный
//     стек со сборкой ловит тот же дефект;
//   - static — образ готовый (nginx:alpine), файлы монтируются томом, собирать
//     нечего и незачем.
//
// Шаблоны каталога, «свой compose» и источник «образ» сюда не попадают: их
// описание пишет платформа и требует готовый образ с digest.
func (a DesiredApp) needsImageBuild() bool {
	return a.FromGit() && a.BuildMethod != buildMethodStatic
}

// imageIDRe — то, что допустимо отдать в `docker image rm` аргументом.
//
// Вывод docker при неудаче идёт в тот же поток, что и полезный: строка
// «Cannot connect to the Docker daemon» без этой проверки уехала бы в команду
// удаления. Короткий идентификатор — 12 шестнадцатеричных знаков, полный —
// sha256 с префиксом.
var imageIDRe = regexp.MustCompile(`^(sha256:)?[0-9a-f]{12,64}$`)

// parseImageIDs разбирает вывод `docker compose images -q`.
//
// Свёртка дубликатов обязательна: два сервиса из одного Dockerfile дают один
// и тот же идентификатор дважды, и без неё удаление шло бы повторно, записывая
// ложную вторую ошибку в журнал агента.
func parseImageIDs(out string) []string {
	var ids []string
	seen := map[string]bool{}

	for _, line := range strings.Split(out, "\n") {
		id := strings.TrimSpace(line)
		if id == "" || seen[id] || !imageIDRe.MatchString(id) {
			continue
		}
		seen[id] = true
		ids = append(ids, id)
	}
	return ids
}

// projectImageIDs — образы, на которых стек работает ПРЯМО СЕЙЧАС.
//
// Читается состояние контейнеров, а не текст compose: нас интересует ровно то,
// что вытеснит пересборка, и только для этого проекта.
//
// При ошибке возвращается nil, и это осознанно означает «неизвестно», а не
// «пусто»: пустой список «до» приводит к пустому списку на удаление, то есть
// сбой чтения оставляет образы на диске вместо того, чтобы снести работающие.
func projectImageIDs(ctx context.Context, dir, envFile string) []string {
	out, err := dockerComposeParsed(ctx, dir, envFile, "images", "-q")
	if err != nil {
		return nil
	}
	return parseImageIDs(out)
}

// replacedImages — образы, которые стек использовал до сборки и больше не
// использует.
//
// Разница списков, а не общий `docker image prune`. Прune на хосте клиента снёс
// бы промежуточные образы соседних стеков и чужих сборок — данные, которые нам
// не принадлежат, — и заодно исказил бы прогноз исчерпания диска в мониторинге:
// тот считает тренд по накопленным замерам, и разовый провал занятости от
// посторонней уборки читается как «место освободилось само».
func replacedImages(before, after []string) []string {
	if len(before) == 0 {
		return nil
	}

	inUse := make(map[string]bool, len(after))
	for _, id := range after {
		inUse[id] = true
	}

	var gone []string
	for _, id := range before {
		if !inUse[id] {
			gone = append(gone, id)
		}
	}
	return gone
}

// buildImages собирает образы стека.
//
// Собирается на КАЖДОМ применении, а не по признаку смены коммита. Применение
// и без того происходит только когда needsApply сказал «да» — новый релиз,
// изменившиеся переменные или повтор после неудачи, — а кеш слоёв docker делает
// пересборку неизменившегося исходника дешёвой. Условие «собирать, только если
// коммит новый» потребовало бы, чтобы сервер присылал коммит; в контракте
// желаемого состояния его нет, в deploy.releases его тоже нет, и выведенный на
// хосте коммит для этого решения не годится: он становится известен уже после
// FetchRepo, то есть после того, как решение принято.

// buildTimeout — потолок на сборку образов.
//
// Единственный шаг выката, у которого не было никакого срока. `docker compose
// build` с шагом, ушедшим в чёрную дыру (apt против молчащего зеркала, сеть без
// таймаута внутри Dockerfile), висел вечно: dockerComposeStreamEnv ждёт
// cmd.Wait(), Apply не возвращается, цикл агента не завершается. С этого момента
// агент переставал забирать желаемое состояние вовсе — «остановить» и «удалить»
// из интерфейса не доезжали никогда. При этом отметка о жизни идёт отдельной
// горутиной, поэтому хост в панели выглядел здоровым.
//
// Значение с запасом: сорок пять минут перекрывают честную сборку тяжёлого
// образа на слабом VPS. Срок агентский, а не из шаблона: это защита агента от
// самого себя, и отдавать её наружу нельзя — присланный ноль означал бы отказ
// на каждом выкате, а сутки вернули бы ровно тот отказ, от которого защищаемся.
const buildTimeout = 45 * time.Minute

func buildImages(ctx context.Context, p Paths, dir, envFile string, onTail func(string)) error {
	ctx, cancel := context.WithTimeout(ctx, buildTimeout)
	defer cancel()

	out, err := dockerComposeStreamEnv(ctx, dir, envFile, onTail, "build")
	if err != nil {
		// Прерывание по сроку отличаем от ошибки сборки: «не уложилась в 45
		// минут» и «не компилируется» чинятся по-разному, а в общем тексте
		// docker они неразличимы — процесс просто убит сигналом.
		if ctx.Err() == context.DeadlineExceeded {
			return fmt.Errorf(
				"сборка образа не уложилась в %s и была прервана: %s",
				buildTimeout, tail(out, 800))
		}
		return fmt.Errorf("docker compose build: %w: %s", err, explainPullLimit(ctx, p, tail(out, 800)))
	}
	return nil
}

// dropUnusedImages убирает образы, вытесненные пересборкой.
//
// Ошибки намеренно не поднимаются наверх: выкат уже состоялся и здоров, и
// объявлять его неудачным из-за неубранного слоя было бы неверно. Docker
// откажет, если образ держит чей-то контейнер (в том числе остановленный) или
// на него ссылается второй тег — оба отказа здесь правильное поведение, а не
// проблема, поэтому пишутся в журнал агента и не более того.
func dropUnusedImages(ctx context.Context, before, after []string) {
	for _, id := range replacedImages(before, after) {
		cmd := exec.CommandContext(ctx, "docker", "image", "rm", id)
		cmd.Env = dockerEnv()
		if out, err := cmd.CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "образ %s не удалён: %v: %s\n", id, err, tail(string(out), 200))
		}
	}
}

// explainPullLimit дописывает причину, когда загрузка образа упёрлась в лимит
// Docker Hub.
//
// ЗАЧЕМ. Анонимный лимит считается не на адрес сервера, а на подсеть
// провайдера: соседи по хостингу выбирают квоту за вас. Установщик прописывает
// зеркало реестра, но на хосте с уже работающими контейнерами НЕ перезапускает
// демон — рестарт остановил бы всё, что там крутится. Настройка остаётся
// записанной и недействующей, и это как раз тот сервер, ради которого
// платформу и подключают.
//
// Человек в этот момент видит сырое `toomanyrequests` и ищет причину в своём
// приложении. Она же на хосте и лечится одной командой.
func explainPullLimit(ctx context.Context, p Paths, output string) string {
	if !strings.Contains(output, "toomanyrequests") &&
		!strings.Contains(output, "rate limit") {
		return output
	}

	// Каталог берём из фактических путей агента, а не из DefaultPaths():
	// установщик разрешает переопределить STATE_DIR, и на таком хосте отметка
	// лежала бы там, куда мы не смотрим.
	marker := filepath.Join(p.StateDir, "registry-mirror-pending")
	if _, err := os.Stat(marker); err != nil {
		return output
	}

	// Отметку ставит установщик и снять её сам не может: человек применяет
	// настройку своим окном обслуживания, о котором установщику ничего не
	// известно. Поэтому спрашиваем демон — иначе подсказка «зеркало не
	// применено» осталась бы навсегда и после того, как его применили.
	if dockerMirrorActive(ctx) {
		os.Remove(marker)
		return output
	}

	return output + "\n\nЗеркало реестра образов на этом сервере записано, но НЕ ПРИМЕНЕНО: " +
		"при подключении на хосте работали контейнеры, и перезапуск Docker остановил бы их все. " +
		"Примените в удобное окно обслуживания: systemctl restart docker"
}

// dockerMirrorActive — демон действительно работает с зеркалом реестра.
//
// Ошибка чтения означает «не знаем» и трактуется как «не применено»: лишняя
// подсказка дешевле молчания в ситуации, ради которой она написана.
func dockerMirrorActive(ctx context.Context) bool {
	cmd := exec.CommandContext(ctx, "docker", "info", "--format", "{{.RegistryConfig.Mirrors}}")
	cmd.Env = dockerEnv()
	out, err := cmd.Output()
	if err != nil {
		return false
	}
	// Пустой список docker печатает как `[]`.
	return strings.TrimSpace(string(out)) != "" && strings.TrimSpace(string(out)) != "[]"
}
