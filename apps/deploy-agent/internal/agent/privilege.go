package agent

import "os"

// Под какими правами агент работает на этом хосте (ADR-0083).
//
// ЗАЧЕМ ЭТО ЗНАТЬ ПЛАТФОРМЕ. Пока хоть один хост работает от root, обещание
// «агент непривилегированный» неверно — и клиент вправе знать, как обстоит
// дело на ЕГО сервере, а не читать общее утверждение на странице
// «Безопасность». Переход идёт с обеих сторон: старые хосты остаются на
// прежнем юните, пока их не переустановят, и режим — единственный способ
// увидеть, где переход уже состоялся.
const (
	// PrivilegeModeProxy — агент работает от своего пользователя и говорит с
	// демоном только через прокси сокета.
	PrivilegeModeProxy = "proxy"
	// PrivilegeModeRoot — агент root-эквивалентен.
	PrivilegeModeRoot = "root"
)

// DetectPrivilegeMode — режим, в котором агент запущен прямо сейчас.
//
// ПОЧЕМУ ДОСТУП К СОКЕТУ СЧИТАЕТСЯ ROOT'ОМ. Непривилегированный пользователь в
// группе `docker` — это тот же root: он запускает контейнер с `privileged` и
// корнем хоста в томе и выходит оттуда администратором машины. Считать такой
// хост «непривилегированным» значило бы показывать клиенту зелёную отметку
// там, где ничего не изменилось, — поэтому режим `proxy` требует ОБОИХ
// условий: не root и разговор через прокси.
func DetectPrivilegeMode() string {
	if os.Geteuid() == 0 {
		return PrivilegeModeRoot
	}
	if os.Getenv("DOCKER_HOST") == "" {
		return PrivilegeModeRoot
	}
	return PrivilegeModeProxy
}
