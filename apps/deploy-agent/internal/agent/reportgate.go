package agent

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"time"
)

// Отсев отчётов, которые ничего не сообщают.
//
// ЗАЧЕМ. Агент опрашивает платформу раз в минуту и на каждом такте отправляет
// шесть запросов: отметку о жизни, желаемое состояние, здоровье, трафик,
// угрозы и список развёрнутого. Сто хостов — это 864 тысячи запросов в сутки,
// круглосуточные 10 rps на ровном месте, и каждый запрос — проверка подписи,
// защита от повтора и запись в базу. При этом в устойчивом состоянии здоровье и
// список развёрнутого побайтно совпадают такт за тактом, а окно угроз на тихом
// хосте пусто. Полезной работы в подавляющем большинстве тактов нет.
//
// ЧТО ДЕЛАЕТ. Отчёт уходит, если его содержимое изменилось ЛИБО если с
// прошлой отправки прошло больше отведённого срока. Второе условие
// обязательно: без него платформа не отличала бы «ничего не изменилось» от
// «агент замолчал», а отметка `health_checked_at` в карточке приложения
// показывала бы час назад при исправном хосте.
//
// ЧЕГО НЕ ДЕЛАЕТ. Не трогает отметку о жизни и желаемое состояние: первая —
// единственный канал, работающий, когда всё плохо, второе — способ узнать о
// действии пользователя. Их частота определяет отзывчивость платформы, и
// экономить на ней нельзя.

// ReportGate помнит, что и когда было отправлено.
//
// Не потокобезопасен намеренно: используется только из основного цикла.
type ReportGate struct {
	sent map[string]gateEntry
	// pendingParsed — разобранные строки лога из окон, которые придержали.
	//
	// Курсор лога двигается независимо от того, ушёл ли отчёт, поэтому
	// придержанное окно теряется навсегда. Панель «Безопасность кромки» при
	// этом печатает «разобрано N запросов за 24 ч» суммой по сохранённым
	// окнам: без переноса счётчика число занижалось бы в разы — молча и без
	// единого признака.
	pendingParsed int64
}

type gateEntry struct {
	hash string
	at   time.Time
}

func NewReportGate() *ReportGate {
	return &ReportGate{sent: map[string]gateEntry{}}
}

// Allow — надо ли отправлять отчёт этого вида.
//
// Решение и отметка разделены сознательно: отметку ставит Mark ПОСЛЕ успешной
// отправки. Иначе сетевой сбой засчитался бы как доставка, и следующая попытка
// не состоялась бы до истечения срока.
func (g *ReportGate) Allow(kind, hash string, now time.Time, maxAge time.Duration) bool {
	prev, ok := g.sent[kind]
	if !ok {
		return true
	}
	if prev.hash != hash {
		return true
	}
	return now.Sub(prev.at) >= maxAge
}

// Mark запоминает успешную отправку.
func (g *ReportGate) Mark(kind, hash string, now time.Time) {
	g.sent[kind] = gateEntry{hash: hash, at: now}
}

// AddPendingParsed откладывает счётчик разобранных строк придержанного окна.
func (g *ReportGate) AddPendingParsed(count int64) {
	if count > 0 {
		g.pendingParsed += count
	}
}

// TakePendingParsed отдаёт накопленное и обнуляет счётчик.
func (g *ReportGate) TakePendingParsed() int64 {
	count := g.pendingParsed
	g.pendingParsed = 0
	return count
}

// PayloadHash — отпечаток отправляемого значения.
//
// По JSON, а не по полям: набор полей меняется вместе с контрактом, и ручной
// список однажды отстал бы молча — то есть отчёт с изменившимся содержимым
// перестал бы отправляться, а заметили бы это по устаревшим данным в
// интерфейсе.
func PayloadHash(value any) string {
	raw, err := json.Marshal(value)
	if err != nil {
		// Несериализуемое значение не отправится и само; пустой отпечаток
		// отличается от любого настоящего, поэтому отсев его пропустит.
		return ""
	}
	sum := sha256.Sum256(raw)
	return hex.EncodeToString(sum[:])
}

// Сроки принудительной отправки.
//
// Пять минут для здоровья и списка развёрнутого: карточка приложения
// показывает «проверено N назад» относительным временем, и разница между одной
// и пятью минутами человеку не видна. Молчание хоста при этом определяется по
// отметке о жизни (`hosts.last_seen_at`, порог 5 минут в presentation.ts), а её
// отсев не касается вовсе.
const (
	HealthReportMaxAge   = 5 * time.Minute
	// StorageProbeMaxAge — как часто пробовать хранилище копий (ADR-0046,
	// решение 7). Час, а не минута такта: проба ПИШЕТ объект (читать наш ключ
	// не умеет), и ежеминутная запись в чужой бакет — это чужой трафик и чужой
	// счёт ради вопроса, ответ на который меняется раз в месяц.
	StorageProbeMaxAge   = time.Hour
	PresenceReportMaxAge = 5 * time.Minute
	// Тихое окно угроз — восемь минут, и это НЕ круглое число «на глаз».
	//
	// Платформа закрывает тревогу и шлёт «отбой» по окну без срабатываний, а
	// группу источника собирает из снапшотов за ПОСЛЕДНИЕ ДЕСЯТЬ МИНУТ
	// (runThreatAlerts.ts: `Date.now() - 10 * 60 * 1000`). Реже десяти минут —
	// и источник периодически исчезает из выборки целиком: syncIncident для
	// него не вызывается, инцидент остаётся открытым навсегда. Восемь минут —
	// запас в две минуты на дрожание тактов и задержку доставки.
	//
	// Инвариант держит тест ниже; при изменении окна на платформе он упадёт.
	QuietThreatMaxAge = 8 * time.Minute
)

// Порог по самому активному адресу заведомо ниже платформенного: там всплеск
// объявляется от 500 запросов за окно и не опускается ниже 125 при любом
// масштабировании (evaluate.ts). Сотня здесь — запас, а не оценка: агент не
// повторяет правила платформы, он лишь отсекает заведомо пустое.
const quietTopTalkerFloor = 100

// ThreatWorthSending — есть ли в окне то, ради чего его стоит отправлять сейчас.
func ThreatWorthSending(w *ThreatWindow) bool {
	if w == nil {
		return false
	}
	if w.Totals.Suspicious > 0 || w.Totals.AuthFailures > 0 {
		return true
	}
	if w.Truncated {
		// Часть событий не поместилась в окно: молчать об этом нельзя.
		return true
	}
	if w.TopTalker != nil && w.TopTalker.Requests >= quietTopTalkerFloor {
		return true
	}
	return false
}
